-- my_csg_pipeline.lua
-- 由文本 CSG 脚本直接构造几何，再走“切片 -> 填充 -> 生成路径 -> 写文件”的自定义流水线
--
-- 与 my_fdm_pipeline.lua 的唯一区别在第 1 步：模型不来自 STL 文件，而是由
-- HsBa.buildCsgModel 用 OCCT DRAW 命令文本现场搭出 B-Rep。后续阶段完全一致，
-- 说明 CSG 模型与网格模型在流水线里是同等公民。
--
-- Lua 环境全局变量:
--   HsBa            : 流水线算子表（buildCsgModel/slice/fill/toGcode/...）
--   model_name      : string, C++ 传入的模型名（可能为空串，此时用下面的默认名）
--   output_path     : string, C++ 传入的默认输出路径（可能为空串）
--   pipeline_config : string, C++ 传入的 JSON 字符串，原样写入 G-code 注释
--   machine         : table, 由 C++ 侧 pipeline_lua_source 预置的参数（可选）
--
-- machine 里本脚本认识的键：
--   csg_script         : CSG 命令文本，缺省为下方 DEFAULT_CSG（支架：底板 + 凸台）
--   layer_height / first_layer_height / wall_count / fill_spacing : 工艺参数
--
-- 返回值: 字符串（作为结果上报给 C++），返回 false/nil 表示流水线失败

-- 一段可读的默认几何：60x40x3 的底板，上面叠一个半径 8、高 12 的圆柱凸台
local DEFAULT_CSG = [[
set    t 3
box    base 60 40 $t
pcylinder boss 8 12
ttranslate boss 30 20 $t
bfuse  result base boss
]]

-- 取参数：优先使用 C++ 注入的 machine 表，其次用脚本默认值
local function param(name, default)
    if type(machine) == "table" and machine[name] ~= nil then
        return machine[name]
    end
    return default
end

function run_pipeline()
    local model = (model_name and #model_name > 0) and model_name or "csg_model"
    local output = (output_path and #output_path > 0) and output_path or "output/custom_csg_pipeline.gcode"
    local csg = param("csg_script", DEFAULT_CSG)
    local layer_height = param("layer_height", 0.2)
    local first_layer_height = param("first_layer_height", 0.25)
    -- ------------------------------------------------------------------
    -- 1. 用 CSG 文本构造模型（失败会抛出 Lua 错误，整条流水线随之终止）
    -- ------------------------------------------------------------------
    HsBa.progress(5, "构造 CSG 模型")
    HsBa.buildCsgModel(model, csg)
    local info = HsBa.modelInfo(model)
    local size_x = info.bbox_max.x - info.bbox_min.x
    local size_y = info.bbox_max.y - info.bbox_min.y
    local height = info.bbox_max.z - info.bbox_min.z
    print(string.format("[Lua CSG] 模型 %s: %.2fx%.2fx%.2f mm, 体积 %.2f mm^3",
        model, size_x, size_y, height, info.volume))
    local layers = HsBa.layerCount(model, layer_height, first_layer_height)
    HsBa.setLayers(layers)
    local z_base = info.bbox_min.z  -- 以模型底面为 Z 起点（与内置流水线一致）
    -- ------------------------------------------------------------------
    -- 2. 逐层切片 + 3. 填充
    -- ------------------------------------------------------------------
    local outlines = {}
    local fills = {}
    local z_heights = {}
    for i = 0, layers - 1 do
        local z = HsBa.layerZ(i, layer_height, first_layer_height)
        local polys = HsBa.slice(model, z_base + z)
        outlines[i + 1] = polys
        z_heights[i + 1] = z
        fills[i + 1] = HsBa.fill(polys, {
            spacing = param("fill_spacing", 0.4),
            angle = 45.0,
            mode = "zigzag",
            borderCount = param("wall_count", 2),
        })
        if i % 20 == 0 then
            HsBa.progress(10 + math.floor(65 * i / math.max(layers, 1)), "切片与填充")
        end
    end
    -- ------------------------------------------------------------------
    -- 4. 组装每层路径数据并生成 G-code（ CSG 几何是自封口的，无需支撑）
    -- ------------------------------------------------------------------
    HsBa.progress(80, "生成路径")
    local path_layers = {}
    for i = 1, layers do
        path_layers[i] = {
            outlines = outlines[i],
            fills = fills[i],
            supports = {},
            zHeight = z_heights[i],
        }
    end
    local gcode = HsBa.toGcode(path_layers, {
        layerHeight = layer_height,
        lineWidth = param("line_width", 0.45),
        printSpeed = param("print_speed", 60),
        travelSpeed = param("travel_speed", 150),
        extrusionMultiplier = 1.0,
        firmware = param("firmware", "marlin"),
        nozzleDiameter = param("nozzle_diameter", 0.4),
        filamentDiameter = param("filament_diameter", 1.75),
        nozzleTemp = param("nozzle_temp", 210),
        bedTemp = param("bed_temp", 60),
    })
    -- ------------------------------------------------------------------
    -- 5. 写文件
    -- ------------------------------------------------------------------
    HsBa.progress(92, "写入 G-code")
    local header = string.format(
        "; Generated by the Custom Lua CSG pipeline (my_csg_pipeline.lua)\n" ..
        "; csg_volume=%.3f layers=%d layer_height=%.3f first_layer_height=%.3f\n" ..
        "; model_size=%.2fx%.2fx%.2f mm\n; config=%s\n",
        info.volume, layers, layer_height, first_layer_height, size_x, size_y, height,
        (pipeline_config and #pipeline_config > 0) and pipeline_config or "n/a")
    HsBa.writeFile(output, header .. gcode)
    HsBa.setOutputPath(output)
    HsBa.removeModel(model)
    HsBa.progress(100, "完成")
    return string.format("Lua CSG 流水线完成: %d 层, 输出 %s", layers, output)
end
